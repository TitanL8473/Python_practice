#把python文件上传至Github,在Github上有一个可以打开的项目
#必须理解的三个区  工作区            暂存区           本地仓库
'''        (你正在改的文件)  (git add 之后)   (git commit 之后)
                │                │                │
                └── git add ─────┘                │
                                 └── git commit ──┘    '''
#一句话：add 是"把哪些改动放进这次存档"，commit 是"按下快门，存档"。
#和写论文的类比：add = 挑出这版要放进附录的图表；commit = 存成「论文_v3_最终版」。